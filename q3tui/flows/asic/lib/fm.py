"""Formality for the ASIC flow: the equivalence-check script (code) and the result reader (code)."""

from __future__ import annotations

import re
from pathlib import Path


def script_text(files: list[Path], top: str, libs: list[str], netlist: Path, svf: Path | None, workdir: Path, options: dict | None = None) -> str:
    """RTL is the reference, the netlist (with the .db libraries) the implementation; `match`, `verify`, and the reports.
    Options: `extra_tcl` (lines before `match`: set_constant, set_user_match, …), `defines` ({name: value}),
    `message_filter` (RTL interpretation messages to accept as warnings, e.g. FMR_ELAB-147: Formality refuses to link on them otherwise)."""
    o = options or {}
    defines = " ".join(f"{k}={v}" if v is not None else str(k) for k, v in (o.get("defines") or {}).items())
    lines = [f"# generated by Q3TUI (asic_lec) — top {top}",
             "set_app_var sh_continue_on_error false"]
    lines += [f"set_mismatch_message_filter -warn {c}" for c in o.get("message_filter") or []]  # (RTL messages you accepted: `options.message_filter`)
    if svf is not None and svf.is_file():
        lines.append(f'set_svf "{svf}"')
    lines += [f'read_db -container r [list {" ".join(chr(34) + x + chr(34) for x in libs)}]',
              "read_sverilog -container r " + (f"-define {{{defines}}} " if defines else "") + "-libname WORK { " + " ".join(f'"{f}"' for f in files) + " }",
              f"set_top r:/WORK/{top}",
              f'read_db -container i [list {" ".join(chr(34) + x + chr(34) for x in libs)}]',
              f'read_verilog -container i -netlist "{netlist}"',
              f"set_top i:/WORK/{top}"]
    lines += [str(x) for x in o.get("extra_tcl") or []]
    lines += ["match", "set result [verify]",
              f'redirect "{workdir / "lec.rpt"}" {{ report_unmatched_points; report_failing_points }}',
              'puts "Q3TUI_LEC_RESULT: [expr {$result ? "SUCCEEDED" : "FAILED"}]"',
              "exit"]
    return "\n".join(lines) + "\n"


def parse_result(log: str) -> dict:
    """{status: equivalent|not_equivalent|inconclusive|unknown, failing, passing, unmatched, unsuppressed (message codes the link stopped on)} from the Formality log."""
    out: dict = {"status": "unknown"}
    codes = re.findall(r"Linking requires the following command to be executed:\s*\n\s*set_mismatch_message_filter -warn (\S+)", log)
    if codes:  # the RTL link stopped on messages nobody accepted
        out["unsuppressed"] = list(dict.fromkeys(codes))
    if re.search(r"Verification SUCCEEDED|Q3TUI_LEC_RESULT: SUCCEEDED", log):
        out["status"] = "equivalent"
    elif re.search(r"Verification FAILED|Q3TUI_LEC_RESULT: FAILED", log):
        out["status"] = "not_equivalent"
    elif re.search(r"Verification INCONCLUSIVE", log):
        out["status"] = "inconclusive"
    for key, pat in (("failing", r"(\d+)\s+Failing compare points"), ("passing", r"(\d+)\s+Passing compare points"),
                     ("unmatched", r"(\d+)\(\d+\)\s+Unmatched reference\(implementation\) compare points")):
        m = re.search(pat, log)
        if m:
            out[key] = int(m.group(1))
    if "RTL interpretation messages were produced" in log:  # (messages you accepted: the result can differ from a simulator's)
        out["rtl_messages"] = True
    return out
