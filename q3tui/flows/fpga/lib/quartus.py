"""Quartus Prime for the FPGA flow (the Intel families: lib/templates.py): the project script and the timing script (code), the report readers
(code). Checked against Quartus Prime Pro 25.1 (Arria 10) and Standard 22.1 (Cyclone V).

`quartus_sh -t synth.tcl` makes a project in the step's work folder (the RTL, the SDC, the folders of the RTL on the search path: a memory's
`ram_init_file` is found beside its RTL), then runs the tools (not the `flow` package, which Standard 22.1 here cannot load): synthesis (Pro
`quartus_syn`, Standard `quartus_map`), the fit when `implement` is set, then the Timing Analyzer on that result (`sta.tcl`: Pro reads the synthesized snapshot, Standard the post-map netlist; after a fit, the final one). The timing
script writes its own lines (`Q3TUI WNS …`), so nothing depends on the layout of Quartus' panels. Utilization: the summary (`.syn` / `.map` /
`.fit.summary`: ALMs, registers, DSP and RAM blocks) and the per-entity table of the report (block memory bits, pins, per instance)."""

from __future__ import annotations

import re
from pathlib import Path

from q3tui.flows.fpga.lib.templates import Template
from q3tui.flows.fpga.lib.vivado import LogTail  # noqa: F401 - (the same reader of a growing log)

PROJECT = "q3tui_fpga"


def _file_kind(f: Path) -> str:
    return {".sv": "SYSTEMVERILOG_FILE", ".svh": "SYSTEMVERILOG_FILE", ".vhd": "VHDL_FILE", ".vhdl": "VHDL_FILE"}.get(f.suffix.lower(), "VERILOG_FILE")


def _q(p) -> str:
    return "{" + str(p) + "}"  # (a Tcl word that keeps spaces and brackets)


def script_text(files: list[Path], top: str, t: Template, device: str, sdc_files: list[Path], workdir: Path, options: dict | None = None) -> str:
    """The project script. Options: `implement` (fit too: numbers after placement and routing, hold judged), `defines` ({name: value}),
    `synth_args` (extra lines of Tcl before the synthesis: assignments)."""
    o = options or {}
    sta = workdir / "sta.tcl"
    lines = [f"# generated by Q3TUI (fpga_synth) — top {top}, {t.title} {device}", f"project_new {PROJECT} -overwrite",
             f'set_global_assignment -name FAMILY "{t.quartus_family}"', f"set_global_assignment -name DEVICE {device}",
             f"set_global_assignment -name TOP_LEVEL_ENTITY {top}"]
    lines += [f"set_global_assignment -name {_file_kind(f)} {_q(f)}" for f in files]
    lines += [f"set_global_assignment -name SDC_FILE {_q(s)}" for s in sdc_files]
    lines += [f"set_global_assignment -name SEARCH_PATH {_q(d)}" for d in dict.fromkeys(f.parent for f in files)]  # (ram_init_file beside its RTL)
    lines += [f"set_global_assignment -name VERILOG_MACRO {_q(f'{k}={v}' if v is not None else k)}" for k, v in (o.get("defines") or {}).items()]
    lines += [str(x) for x in o.get("synth_args") or []]
    lines.append("project_close")
    # the tools themselves, not the `flow` package (Standard 22.1 here cannot load it: libpython3.7m): their output in this log
    for tool in ["quartus_syn" if t.edition == "pro" else "quartus_map", *(["quartus_fit"] if o.get("implement") else [])]:
        lines.append(f"if {{[catch {{exec {tool} {PROJECT} >@ stdout 2>@ stderr}} msg]}} {{ puts \"Error: Q3TUI {tool} failed: $msg\"; exit 1 }}")
    # the Timing Analyzer on what was made (a failure is said; the reports of the synthesis stay)
    lines.append(f"if {{[catch {{exec quartus_sta -t {_q(sta)} >@ stdout 2>@ stderr}} msg]}} {{ puts \"Error: Q3TUI timing analysis failed: $msg\" }}")
    return "\n".join(lines) + "\n"


def sta_text(t: Template, sdc_files: list[Path], workdir: Path, implemented: bool) -> str:
    """The Timing Analyzer script: the worst setup and hold paths and each clock domain's slack and TNS as `Q3TUI …` lines in timing.rpt, the
    Fmax summary (fmax.rpt) and the worst paths (paths.rpt)."""
    snapshot = "" if implemented else ("-snapshot synthesized" if t.edition == "pro" else "-post_map")
    out = workdir / "timing.rpt"
    return "\n".join([
        f"project_open {PROJECT}", f"create_timing_netlist {snapshot}".rstrip(), *(f"read_sdc {_q(s)}" for s in sdc_files), "update_timing_netlist",
        f"set fh [open {_q(out)} w]",
        f"puts $fh \"Q3TUI STAGE {'final' if implemented else 'synthesized'}\"",
        "foreach_in_collection p [get_timing_paths -setup -npaths 1] {",
        '  puts $fh "Q3TUI WNS [get_path_info $p -slack]"',
        '  puts $fh "Q3TUI FROM [get_node_info -name [get_path_info $p -from]]"',
        '  puts $fh "Q3TUI TO [get_node_info -name [get_path_info $p -to]]"',
        '  puts $fh "Q3TUI LEVELS [get_path_info $p -num_logic_levels]"',
        '  puts $fh "Q3TUI DATA_DELAY [get_path_info $p -data_delay]"',
        "}",
        'foreach_in_collection h [get_timing_paths -hold -npaths 1] { puts $fh "Q3TUI WHS [get_path_info $h -slack]" }',
        'foreach d [get_clock_domain_info -setup] { puts $fh "Q3TUI CLOCK [lindex $d 0] [lindex $d 1] [lindex $d 2]" }',
        "close $fh",
        f"report_clock_fmax_summary -file {_q(workdir / 'fmax.rpt')}",
        f"report_timing -setup -npaths 5 -detail path_only -file {_q(workdir / 'paths.rpt')}",
        "delete_timing_netlist", "project_close"]) + "\n"


# -- reports -------------------------------------------------------------------------------------------------------

_NUM = r"([\d,]+(?:\.\d+)?)"
_SUMMARY = {  # summary label → (our key, what it is)
    "Logic utilization estimate (in ALMs)": ("lut", "ALMs"), "Logic utilization (in ALMs)": ("lut", "ALMs"),
    "Logic utilization (in LEs)": ("lut", "LEs"), "Total logic elements": ("lut", "LEs"),
    "Total registers": ("ff", "registers"), "Total pins": ("io", "pins"), "Total RAM Blocks": ("bram_tile", "RAM blocks"),
    "Total block memory bits": ("mem_bits", "block memory bits"), "Total DSP Blocks": ("dsp", "DSP blocks"),
    "Estimated DSP Blocks Post-Merging": ("dsp", "DSP blocks"), "Embedded Multiplier 9-bit elements": ("dsp", "9-bit multipliers"),
}


def _int(s: str) -> int | float:
    v = float(s.replace(",", ""))
    return int(v) if v == int(v) else v


def parse_utilization(summary: str, report: str = "") -> dict:
    """{key: {used, available, pct, label}} from the summary (available / pct when Quartus gives them, else None), with the block memory bits
    and pins of the per-entity table's top row when the summary lacks them (Pro's synthesis summary has no memory line)."""
    out: dict[str, dict] = {}
    for line in summary.splitlines():
        if ":" not in line:
            continue
        name, _, value = (x.strip() for x in line.partition(" : "))
        hit = _SUMMARY.get(name)
        if not hit or hit[0] in out:
            continue
        m = re.match(rf"{_NUM}\s*(?:/\s*{_NUM}\s*\(\s*(<)?\s*{_NUM}\s*%\s*\))?", value)
        if m:
            used, avail = _int(m.group(1)), (_int(m.group(2)) if m.group(2) else None)
            pct = float(m.group(4)) if m.group(4) and not m.group(3) else None
            if avail and pct is None:  # ("< 1 %": the real share)
                pct = round(100.0 * used / avail, 3)
            out[hit[0]] = {"used": used, "available": avail, "pct": pct, "label": hit[1]}
    top = entity_top(report)
    for key, col, label in (("mem_bits", "Block Memory Bits", "block memory bits"), ("io", "Pins", "pins")):
        if key not in out and col in top:
            out[key] = {"used": top[col], "available": None, "pct": None, "label": label}
    return out


def entity_table(report: str) -> str:
    """The "Resource Utilization by Entity" table of a Quartus report (the per-instance usage: where the logic went)."""
    m = re.search(r"^;[^;\n]*Resource Utilization by Entity\s*;\s*$", report, re.M)  # (the table's title line: not the contents, not a setting)
    if not m:
        return ""
    block = report[report.rfind("\n", 0, max(m.start() - 1, 0)) + 1:]  # (from the border line above the title)
    end = re.search(r"\n\s*\n", block)
    return block[: end.start()] if end else block


def entity_top(report: str) -> dict[str, int | float]:
    """The table's first data row (the top entity, totals): {column: number} (the first number of "27 (27)")."""
    rows = [r for r in entity_table(report).splitlines() if r.startswith(";")]
    if len(rows) < 3:
        return {}
    head = [c.strip() for c in rows[1].strip(";").split(";")]
    vals = [c.strip() for c in rows[2].strip(";").split(";")]
    out = {}
    for h, v in zip(head, vals):
        m = re.match(_NUM, v)
        if m:
            out[h] = _int(m.group(1))
    return out


def parse_timing(text: str, fmax_rpt: str = "") -> dict:
    """The `Q3TUI …` lines: setup `wns_ns`, hold `whs_ns`, `tns_ns` (the clock domains' TNS added), and `fmax_mhz` (the Fmax summary's
    restricted Fmax of the first clock)."""
    out: dict = {}
    tns = 0.0
    for line in text.splitlines():
        parts = line.split()
        if len(parts) < 3 or parts[0] != "Q3TUI":
            continue
        try:
            if parts[1] == "WNS":
                out["wns_ns"] = float(parts[2])
            elif parts[1] == "WHS":
                out["whs_ns"] = float(parts[2])
            elif parts[1] == "CLOCK" and len(parts) >= 5:
                tns += float(parts[4])
                out["tns_ns"] = round(tns, 3)
        except ValueError:
            continue
    m = re.search(r"^;\s*([\d.]+)\s*MHz\s*;\s*([\d.]+)\s*MHz\s*;", fmax_rpt, re.M)
    if m:
        out["fmax_mhz"] = float(m.group(2))
    out["met"] = out.get("wns_ns", -1.0) >= 0
    return out


def critical_path(text: str) -> dict:
    """The worst setup path of the `Q3TUI …` lines: slack, source, destination, logic levels, data path delay."""
    out: dict = {}
    for line in text.splitlines():
        parts = line.split(maxsplit=2)
        if len(parts) < 3 or parts[0] != "Q3TUI":
            continue
        key = {"WNS": "slack_ns", "FROM": "source", "TO": "destination", "LEVELS": "logic_levels", "DATA_DELAY": "data_path_ns"}.get(parts[1])
        if key:
            try:
                out[key] = float(parts[2]) if key.endswith("_ns") else (int(float(parts[2])) if key == "logic_levels" else parts[2])
            except ValueError:
                continue
    return out


def tool_version(log: str) -> str:
    m = re.search(r"Version (\d+\.\d+(?:\.\d+)?)[^\n]*?(Pro|Standard|Lite)? Edition", log)
    return f"Quartus Prime {m.group(1)}" + (f" {m.group(2)}" if m and m.group(2) else "") if m else "Quartus Prime"


_PHASE = re.compile(r"^Info(?: \(\d+\))?: (Running Quartus Prime \w[\w ]*|Quartus Prime \w[\w ]* was successful.*|Started post-fitting delay annotation|"
                    r"Starting Fitter periphery placement operations|Fitter (?:placement|routing) (?:preparation )?operations? (?:beginning|ending))")


def phase_line(line: str) -> str | None:
    """A line of the Quartus log worth showing as progress (which tool runs, which finished)."""
    m = _PHASE.match(line.strip())
    return m.group(1) if m else None
