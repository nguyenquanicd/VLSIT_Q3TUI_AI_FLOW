"""Yosys + nextpnr for the FPGA flow (the open-source templates): the synthesis script and the place-and-route arguments (code), the
log readers (code).

Yosys maps the RTL to the family's cells (`synth_ecp5`, `synth_ice40`) and writes a JSON netlist; nextpnr places and routes it
out of context (no pins) against the clock frequencies of the SDC and reports Fmax per clock, the critical path and the utilisation
of the device. nextpnr has no hold analysis: the report judges setup only."""

from __future__ import annotations

import re
from pathlib import Path

from q3tui.flows.fpga.lib.templates import Template
from q3tui.flows.fpga.lib.vivado import LogTail  # noqa: F401 - (the same reader of a growing log)


def yosys_script(files: list[Path], top: str, t: Template, json_out: Path, stat_out: Path, options: dict | None = None) -> str:
    """The Yosys script. Options: `frontend` ("verilog" default | "slang": the yosys-slang plugin), `defines` ({name: value}),
    `synth_args` (extra arguments of the synthesis command)."""
    o = options or {}
    defs = [f"-D{k}={v}" if v is not None else f"-D{k}" for k, v in (o.get("defines") or {}).items()]
    names = " ".join(f'"{f}"' for f in files)
    lines = [f"# generated by Q3TUI (fpga_synth) — top {top}, {t.title}"]
    if str(o.get("frontend") or "verilog") == "slang":
        lines += ["plugin -i slang", f"read_slang --top {top} {' '.join(defs)} {names}".replace("  ", " ")]
    else:
        lines.append(f"read_verilog -sv {' '.join(defs)} {names}".replace("  ", " "))
    lines += [f"{t.synth} -top {top} -json \"{json_out}\" {' '.join(map(str, o.get('synth_args') or []))}".rstrip(), f'tee -o "{stat_out}" stat']
    return "\n".join(lines) + "\n"


def pnr_args(t: Template, device: str, package: str, speed: str, json_in: Path, log: Path, clocks: list[dict], lpf: Path | None = None) -> list[str]:
    """The nextpnr arguments. `clocks`: [{name, port, period_ns}] of the SDC: `--freq` is the fastest one; ECP5 gets a constraint file
    with one FREQUENCY line per clock when there are several."""
    freq = max((1000.0 / c["period_ns"] for c in clocks), default=100.0)
    args = [f"--{device}", "--package", package]
    if t.family == "ECP5":
        args += ["--speed", speed, "--out-of-context"]
        if lpf is not None and len(clocks) > 1:
            args += ["--lpf", str(lpf), "--lpf-allow-unconstrained"]
    else:
        args += ["--pcf-allow-unconstrained"]  # (no out-of-context mode: the IOs are placed by nextpnr)
    return [*args, "--json", str(json_in), "--freq", f"{freq:g}", "--timing-allow-fail", "--log", str(log), "-q"]


def lpf_text(clocks: list[dict]) -> str:
    return "".join(f'FREQUENCY PORT "{c["port"]}" {1000.0 / c["period_ns"]:g} MHZ;\n' for c in clocks)


# -- logs --------------------------------------------------------------------------------------------------------------------

_UTIL = re.compile(r"^(?:Info:)?\s*(\w+):\s+(\d+)/\s*(\d+)\s+(\d+)%\s*$")


def parse_utilization(pnr_log: str, stat: str, t: Template) -> dict:
    """{lut, ff, bram_tile, dsp, io: {used, available, pct}} from nextpnr's last "Device utilisation:" block (and, for iCE40, whose logic
    cell holds a LUT and a flip-flop, the flip-flop count of Yosys' `stat`)."""
    block: dict[str, tuple[int, int]] = {}
    inside = False
    for line in pnr_log.splitlines():
        if "Device utilisation:" in line:
            inside, block = True, {}
            continue
        if inside:
            m = _UTIL.match(line.replace("\t", " "))
            if m:
                block[m.group(1)] = (int(m.group(2)), int(m.group(3)))
            elif not line.strip() or not line.startswith("Info:"):
                inside = False
    out: dict = {}
    for key, name in t.resources.items():
        if name in block:
            used, avail = block[name]
            out[key] = {"used": used, "available": avail, "pct": round(100.0 * used / avail, 2) if avail else 0.0}
    if t.family == "iCE40" and "lut" in out:
        ffs = sum(int(n) for n, cell in re.findall(r"^\s+(\d+)\s+(SB_DFF\w*)\s*$", stat, re.M))
        avail = out["lut"]["available"]
        out["ff"] = {"used": ffs, "available": avail, "pct": round(100.0 * ffs / avail, 2) if avail else 0.0}
    return out


_FMAX = re.compile(r"Max frequency for clock '([^']+)':\s+([\d.]+) MHz \((PASS|FAIL) at ([\d.]+) MHz\)")


def fmax_lines(pnr_log: str) -> list[tuple[str, float, bool, float]]:
    """(clock, Fmax MHz, met, target MHz) of the last analysis of each clock (the one after routing)."""
    last: dict[str, tuple[str, float, bool, float]] = {}
    for m in _FMAX.finditer(pnr_log):
        last[m.group(1)] = (m.group(1), float(m.group(2)), m.group(3) == "PASS", float(m.group(4)))
    return list(last.values())


def parse_timing(timing_rpt: str) -> dict:
    """{wns_ns, fmax_mhz, met, clocks}: the worst setup slack against the target period of each clock (period − 1 / Fmax), the lowest Fmax.
    nextpnr gives no total negative slack and no hold slack."""
    rows = fmax_lines(timing_rpt)
    if not rows:
        return {}
    slack = {c: round(1000.0 / target - 1000.0 / f, 3) for c, f, _ok, target in rows}
    return {"wns_ns": min(slack.values()), "fmax_mhz": round(min(f for _c, f, _o, _t in rows), 2), "met": all(ok for _c, _f, ok, _t in rows),
            "clocks": {c: {"fmax_mhz": f, "target_mhz": target, "slack_ns": slack[c]} for c, f, _o, target in rows}}


def timing_report(pnr_log: str) -> str:
    """The lines of `timing.rpt`: the last Fmax line of each clock."""
    return "".join(f"Max frequency for clock '{c}': {f:g} MHz ({'PASS' if ok else 'FAIL'} at {t:g} MHz)\n" for c, f, ok, t in fmax_lines(pnr_log))


def critical_path_text(pnr_log: str) -> str:
    """The last "Critical path report" of the log, as the text of `paths.rpt`."""
    i = pnr_log.rfind("Critical path report for clock")
    if i < 0:
        return ""
    lines = pnr_log[i:].splitlines()
    out = []
    for ln in lines:
        if out and ("Max frequency" in ln or ln.startswith(("Info: Slack histogram", "Info: Program"))):
            break
        out.append(re.sub(r"^(Info|Warning): ", "", ln))
    return "\n".join(out).rstrip() + "\n"


def critical_path(paths_rpt: str) -> dict:
    """The worst path of `paths.rpt`: source, destination, logic levels, data path delay (clock to the last sink)."""
    out: dict = {}
    m = re.search(r"^\s*clk-to-q\s+[\d.]+\s+[\d.]+\s+Source\s+(\S+)", paths_rpt, re.M)
    if m:
        out["source"] = m.group(1)
    sinks = re.findall(r"^\s+Sink\s+(\S+)", paths_rpt, re.M)
    if sinks:
        out["destination"] = sinks[-1]
    out["logic_levels"] = len(re.findall(r"^\s+logic\s+[\d.]+\s+[\d.]+\s+Source", paths_rpt, re.M))
    tot = re.findall(r"^\s+(?:logic|routing|clk-to-q|setup)\s+-?[\d.]+\s+(-?[\d.]+)\s", paths_rpt, re.M)
    if tot:
        out["data_path_ns"] = float(tot[-1])
    return out


_YPHASE = re.compile(r"^\d+(?:\.\d+)*\.\s+Executing (\w+) pass")
_PPHASE = re.compile(r"^Info:\s+(Running main analytical placer|Routing\.\.|Setting up routing|Running router1|Running router2|Checksum|Placed \d+ cells)")


def phase_line(line: str) -> str | None:
    """A Yosys / nextpnr log line worth showing as progress (the passes of Yosys, the stages of nextpnr), else None."""
    line = line.strip()
    m = _YPHASE.match(line)
    if m and m.group(1) in {"PROC", "FLATTEN", "ALUMACC", "MEMORY", "TECHMAP", "ABC", "ABC9", "OPT", "DFFLEGALIZE", "SYNTH", "AUTONAME"}:
        return m.group(1).lower()
    m = _PPHASE.match(line)
    return line[6:90] if m else None


def tool_version(yosys_log: str) -> str:
    m = re.search(r"Yosys (\d+\.\d+(?:\+\d+)?)", yosys_log)
    return f"Yosys {m.group(1)} + nextpnr" if m else "Yosys + nextpnr"
