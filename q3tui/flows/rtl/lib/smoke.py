"""The smoke test's mechanics (code): file lists, compile (tool role `sim`), run (role `run`), reading the result lines.

The testbench prints one `SMOKE_RESULT <id> PASS|FAIL [what was expected / seen]` per behaviour and a `SMOKE_SUMMARY total=<n> failed=<n>`;
anything else (no result line, a timeout, a non-zero exit with no FAIL) is a failure, never a pass."""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

TOP = "tb_smoke"
TB_FILE = "tb_smoke.sv"
_RESULT = re.compile(r"\bSMOKE_RESULT\s+(\S+)\s+(PASS|FAIL)\b[ \t]*(.*)$", re.M | re.I)
_SUMMARY = re.compile(r"\bSMOKE_SUMMARY\s+total=(\d+)\s+failed=(\d+)", re.I)


@dataclass
class Outcome:
    status: str  # pass | fail | timeout | no_result
    results: dict[str, dict] = field(default_factory=dict)  # id -> {status, detail}
    reason: str = ""
    log: str = ""

    def to_dict(self) -> dict:
        return {"status": self.status, "results": self.results, "reason": self.reason, "log": self.log}


def parse_run(text: str, returncode: int | None, timed_out: bool, log: str = "") -> Outcome:
    results = {m.group(1): {"status": m.group(2).upper(), "detail": m.group(3).strip()} for m in _RESULT.finditer(text)}
    if timed_out:
        return Outcome("timeout", results, "the simulation did not finish in time", log)
    if not results:
        return Outcome("no_result", results, "no SMOKE_RESULT line in the output" + ("" if returncode in (0, None) else f"; exit code {returncode}"), log)
    failed = [i for i, r in results.items() if r["status"] != "PASS"]
    s = _SUMMARY.search(text)
    if failed:
        return Outcome("fail", results, f"{len(failed)} of {len(results)} behaviour(s) failed: {', '.join(failed)}", log)
    if s and (int(s.group(2)) or int(s.group(1)) != len(results)):
        return Outcome("fail", results, f"SMOKE_SUMMARY ({s.group(0)}) does not match the {len(results)} result line(s)", log)
    return Outcome("pass", results, "", log)


def filelists(project_root: Path, rtl_files: list[Path], tb: Path, work: Path) -> tuple[Path, Path]:
    """(deliverable filelist with project-relative paths next to the testbench, absolute one for the tool)."""
    def rel(p: Path) -> str:
        try:
            return str(p.resolve().relative_to(project_root.resolve()))
        except ValueError:
            return str(p)

    (tb.parent / "filelist.f").write_text("// Generated by Q3TUI (rtl flow, smoke); paths relative to the project root\n"
                                          + "".join(rel(p) + "\n" for p in [*rtl_files, tb]))
    work.mkdir(parents=True, exist_ok=True)
    absf = work / "filelist_smoke_abs.f"
    absf.write_text("".join(str(p.resolve()) + "\n" for p in [*rtl_files, tb]))
    return tb.parent / "filelist.f", absf


def compile_tb(ts, project_root: Path, work: Path, rtl_files: list[Path], tb: Path):
    from q3tui.eda.tools import check_broken, run_role

    _, absf = filelists(project_root, rtl_files, tb, work)
    res = run_role(ts, "sim", work, {"filelist": absf, "top": TOP, "files": [str(p) for p in [*rtl_files, tb]], "incdirs": [],
                                     "workdir": work, "project": project_root}, log_name="smoke_compile.log")
    check_broken(res, "sim")  # (a compile that fails with no error line is the command's problem, not the code's)
    return res


def run_tb(ts, project_root: Path, work: Path) -> Outcome:
    from q3tui.eda.tools import run_role

    res = run_role(ts, "run", work, {"tc": "smoke", "top": TOP, "workdir": work, "project": project_root}, log_name="smoke_run.log")
    text = Path(res.log_path).read_text(errors="replace") if res.log_path and Path(res.log_path).is_file() else ""
    return parse_run(text, res.returncode, res.timed_out, res.log_path or "")


def compile_errors(res) -> list[str]:
    errs = [d for d in res.diagnostics if d.severity == "error"]
    return [f"{d.file}:{d.line} {d.message}" if d.file else d.message for d in errs] or ([] if res.ok else [res.summary])


def show_outcome(out: Outcome) -> str:
    rows = [f"{i}: {r['status']}" + (f" — {r['detail']}" if r["detail"] else "") for i, r in out.results.items()]
    return "\n".join([f"smoke run: {out.status.upper()}" + (f" ({out.reason})" if out.reason else ""), *rows])
