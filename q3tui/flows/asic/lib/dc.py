"""Design Compiler for the ASIC flow: the synthesis script (code) and the report readers (code).

The script analyzes / elaborates the RTL, sources `constraints/sdc/sdc.tcl` (the same constraints the FPGA flow uses), compiles, writes the
netlist, the constraints and the Formality guidance (SVF), and the reports of `REPORTS` next to itself."""

from __future__ import annotations

import re
from pathlib import Path

from q3tui.flows.asic.lib.base import REPORTS


def script_text(files: list[Path], top: str, libs: list[str], sdc_tcl: Path | None, workdir: Path, netlist: Path, options: dict | None = None) -> str:
    """The Design Compiler Tcl script. Options: `compile` (default `compile_ultra`), `max_paths` (worst paths in timing.rpt),
    `extra_tcl` (lines after `link`: set_max_area, dont_use, operating conditions…), `defines` ({name: value})."""
    o = options or {}
    quoted = " ".join(f'"{x}"' for x in libs)
    defines = " ".join(f"{k}={v}" if v is not None else str(k) for k, v in (o.get("defines") or {}).items())
    lines = [f"# generated by Q3TUI (asic_synth) — top {top}",
             "set_app_var sh_continue_on_error false",
             f'define_design_lib WORK -path "{workdir / "WORK"}"',
             f'set_svf "{workdir / (top + ".svf")}"',  # (the guidance Formality needs for the changes compile makes; before the design is read)
             f"set_app_var target_library [list {quoted}]",
             f'set_app_var link_library [list "*" {quoted}]',
             "analyze -format sverilog -work WORK " + (f"-define {{{defines}}} " if defines else "") + "{ " + " ".join(f'"{f}"' for f in files) + " }",
             f"elaborate {top} -work WORK", f"current_design {top}", "link", "uniquify"]
    lines += [str(x) for x in o.get("extra_tcl") or []]
    if sdc_tcl is not None:
        lines.append(f'source -echo "{sdc_tcl}"')
    n = int(o.get("max_paths") or 5)
    out = lambda name: f'"{workdir / name}"'  # noqa: E731
    lines += [str(o.get("compile") or "compile_ultra"),
              "change_names -rules verilog -hierarchy",
              f'file mkdir "{netlist.parent}"',
              f'write -format verilog -hierarchy -output "{netlist}"',
              f'write -format ddc -hierarchy -output "{netlist.with_suffix(".ddc")}"',
              f'write_sdc "{netlist.with_suffix(".sdc")}"',
              f"redirect {out('area.rpt')} {{ report_area -hierarchy }}",
              f"redirect {out('timing.rpt')} {{ report_timing -max_paths {n} -nworst 1 -delay_type max -path full }}",
              f"redirect {out('qor.rpt')} {{ report_qor }}",
              f"redirect {out('power.rpt')} {{ report_power }}",
              f"redirect {out('constraints.rpt')} {{ report_constraint -all_violators }}",
              f"redirect {out('check_design.rpt')} {{ check_design }}",
              f"redirect {out('check_timing.rpt')} {{ check_timing }}",
              "exit"]
    return "\n".join(lines) + "\n"


