def _num(s: str) -> float | None:
    try:
        return float(s.replace(",", ""))
    except ValueError:
        return None


def parse_area(text: str) -> dict:
    """{total_um2, combinational_um2, sequential_um2, cells, sequential_cells, ports} from report_area."""
    out: dict = {}
    for key, pat in (("total_um2", r"Total cell area:\s+([\d.,]+)"), ("combinational_um2", r"Combinational area:\s+([\d.,]+)"),
                     ("sequential_um2", r"Noncombinational area:\s+([\d.,]+)"), ("cells", r"Number of cells:\s+(\d+)"),
                     ("sequential_cells", r"Number of sequential cells:\s+(\d+)"), ("ports", r"Number of ports:\s+(\d+)")):
        m = re.search(pat, text)
        if m and _num(m.group(1)) is not None:
            v = _num(m.group(1))
            out[key] = int(v) if key in ("cells", "sequential_cells", "ports") else v
    return out


def parse_timing(text: str) -> dict:
    """The worst setup path of report_timing (the first `slack`): {slack_ns, met, startpoint, endpoint, path_group, data_arrival_ns}."""
    out: dict = {}
    m = re.search(r"slack \((MET|VIOLATED)[^)]*\)\s+(-?[\d.]+)", text)
    if m:
        out["met"] = m.group(1) == "MET"
        out["slack_ns"] = float(m.group(2))
    for key, pat in (("startpoint", r"Startpoint:\s+(\S+)"), ("endpoint", r"Endpoint:\s+(\S+)"), ("path_group", r"Path Group:\s+(\S+)")):
        m = re.search(pat, text)
        if m:
            out[key] = m.group(1)
    m = re.search(r"data arrival time\s+(-?[\d.]+)", text)
    if m:
        out["data_arrival_ns"] = float(m.group(1))
    return out


def parse_qor(text: str) -> dict:
    """From report_qor (one block per path group): the worst setup slack `wns_ns`, the total negative slack `tns_ns`, the number of
    violating paths, the most levels of logic, the hold violation."""
    def vals(pat: str) -> list[float]:
        return [float(x) for x in re.findall(pat, text)]

    out: dict = {}
    for key, pat, pick in (("wns_ns", r"Critical Path Slack:\s+(-?[\d.]+)", min), ("tns_ns", r"Total Negative Slack:\s+(-?[\d.]+)", sum),
                           ("violating_paths", r"No\. of Violating Paths:\s+(\d+(?:\.\d+)?)", sum), ("logic_levels", r"Levels of Logic:\s+(\d+(?:\.\d+)?)", max),
                           ("hold_violation_ns", r"Total Hold Violation:\s+(-?[\d.]+)", sum)):
        v = vals(pat)
        if v:
            r = pick(v)
            out[key] = int(r) if key in ("violating_paths", "logic_levels") else round(r, 4)
    return out


def parse_groups(qor: str, periods: dict[str, float] | None = None) -> list[dict]:
    """One entry per clock path group of report_qor: {group, slack_ns, period_ns, target_mhz, fmax_mhz}. The Fmax is what the clock could run at
    with the worst setup path of the group as it is now: 1000 / (period − slack). `bound` is "estimate" when the clock is missed (what the library can reach, about) and "at_least" when it is met (the tool stops at zero slack: it can go faster). `periods` ({clock name: period}) wins over the report's
    own (rounded) period. Internal groups (`**async_default**`, …) are left out."""
    out = []
    for m in re.finditer(r"Timing Path Group '([^']+)'(.*?)(?=Timing Path Group|\n\s*Cell Count|\Z)", qor, re.S):
        name, body = m.group(1), m.group(2)
        if name.startswith("**"):
            continue
        sl = re.search(r"Critical Path Slack:\s+(-?[\d.]+)", body)
        pd = re.search(r"Critical Path Clk Period:\s+([\d.]+)", body)
        period = (periods or {}).get(name) or (float(pd.group(1)) if pd else None)
        if not sl or not period:
            continue
        slack = float(sl.group(1))
        usable = period - slack
        # (met: the tool stops optimizing at zero slack, so the number is what it reached, not the limit: "at_least")
        out.append({"group": name, "slack_ns": slack, "period_ns": period, "target_mhz": round(1000.0 / period, 1),
                    "fmax_mhz": round(1000.0 / usable, 1) if usable > 0 else None, "bound": "at_least" if slack >= 0 else "estimate"})
    return out


def parse_version(log: str) -> str:
    m = re.search(r"Version:\s+(\S+)", log)
    return f"Design Compiler {m.group(1)}" if m else "Design Compiler"


def parse_power(text: str) -> dict:
    """{dynamic_uw, leakage_uw, total_uw} from report_power (the unit of the report is converted to µW)."""
    units = {"pW": 1e-6, "nW": 1e-3, "uW": 1.0, "mW": 1e3, "W": 1e6}
    out: dict = {}
    for key, pat in (("dynamic_uw", r"Total Dynamic Power\s*=\s*([\d.eE+-]+)\s*(\w+)"), ("leakage_uw", r"Cell Leakage Power\s*=\s*([\d.eE+-]+)\s*(\w+)")):
        m = re.search(pat, text)
        if m and m.group(2) in units and _num(m.group(1)) is not None:
            out[key] = round(float(m.group(1)) * units[m.group(2)], 4)
    if len(out) == 2:
        out["total_uw"] = round(out["dynamic_uw"] + out["leakage_uw"], 4)
    return out


def violations(text: str) -> list[str]:
    """The lines of report_constraint -all_violators that end in a violated slack (empty when none). Lines that say "VIOLATED: increase significant
    digits" are a few 1e-4 below the limit, which the report cannot show: not violations."""
    return [ln.strip() for ln in text.splitlines() if re.search(r"\(VIOLATED\)\s*$", ln)]  # ("VIOLATED: increase significant digits" is a rounding artifact)


def check_design(text: str) -> dict[str, int]:
    """{Error/Warning: count} of check_design (latches, unconnected ports, multiple drivers show as warnings with their codes)."""
    return {k: len(re.findall(rf"^{k}:", text, re.M)) for k in ("Error", "Warning") if re.search(rf"^{k}:", text, re.M)}


def unconstrained(text: str) -> list[str]:
    """The warnings of check_timing (no clock, unconstrained endpoints, …), one line each."""
    return [ln.strip() for ln in text.splitlines() if ln.startswith("Warning:")][:10]


_PHASE = re.compile(r"^\s*(?:Beginning|Running|Loading db|Elaborating|Compiling|Starting)\b.*$")


def phase_line(line: str) -> str | None:
    """A log line worth showing as progress ("Beginning Mapping Optimizations", "Loading db file …")."""
    return line.strip()[:100] if _PHASE.match(line) else None


class LogTail:
    """Reads what a growing log file got since the last `new()` (the tool writes it while it runs)."""

    def __init__(self, path: Path):
        self.path, self.pos = path, 0

    def new(self) -> list[str]:
        try:
            with self.path.open("rb") as fh:
                fh.seek(self.pos)
                data = fh.read()
        except OSError:
            return []
        end = data.rfind(b"\n") + 1
        self.pos += end
        return data[:end].decode(errors="replace").splitlines()


