"""The review ledger and report of the `uvm_vip` backend: for every open issue of the verification contract, who decided it.

Classes: `user_answered` (the user typed an answer), `user_accepted_default` (the user reviewed the issue and accepted its default,
recorded in `schemas/dv_review_decisions.json`), `auto_default` (the default was accepted without a review: a gate in auto mode, or
--yes), `pending` (nobody decided yet). Rendered into `schemas/dv_review.json` and `docs/dv_review_report.md` (rule DUT-DV-006)."""

from __future__ import annotations

from pathlib import Path

from q3tui.core.project import read_json, write_json
from q3tui.flows.vlsit.tb.uvm.intent import question_id
from q3tui.steps.common import load_answers

DECISIONS_FILE = "dv_review_decisions.json"
CLASSES = ("user_answered", "user_accepted_default", "auto_default", "pending")


def decisions_path(project) -> Path:
    return project.schemas_dir / DECISIONS_FILE


def issue_sha(o) -> str:
    """Fingerprint of what the user reviewed: the question, its default, the requirements and the kind."""
    import hashlib
    import json

    return hashlib.sha256(json.dumps([o.kind, o.question, o.default_assumption, sorted(o.requirement_ids)]).encode()).hexdigest()[:16]


def record_decision(project, issue, decision: str, by: str, at: str, note: str = "") -> None:
    """Record a review decision of the user (`accept_default`) for an open issue (an OpenIssue); never inferred, always attributed.
    The decision is bound to the issue's text: if the issue changes later, the decision no longer counts."""
    if decision != "accept_default":
        raise ValueError("decision must be 'accept_default' (an answer goes through the question's answer instead)")
    data = read_json(decisions_path(project), default={}) or {}
    data[question_id(issue.id)] = {"decision": decision, "by": by, "at": at, "note": note, "issue_sha": issue_sha(issue)}
    write_json(decisions_path(project), data)


def ledger(contract, answers: dict[str, str], decisions: dict[str, dict], auto_defaults: dict[str, str]) -> list[dict]:
    rows = []
    for o in contract.open_issues:
        qid = question_id(o.id)
        if qid in answers:
            cls, detail = "user_answered", {"answer": answers[qid]}
        elif (decisions.get(qid) or {}).get("decision") == "accept_default" and decisions[qid].get("issue_sha") == issue_sha(o):
            d = decisions[qid]
            cls, detail = "user_accepted_default", {"by": d.get("by", ""), "at": d.get("at", ""), "note": d.get("note", ""), "default": o.default_assumption}
        elif qid in auto_defaults:
            cls, detail = "auto_default", {"default": auto_defaults[qid]}
        else:
            stale = (decisions.get(qid) or {}).get("decision") == "accept_default"  # reviewed, but the issue changed since
            cls, detail = "pending", ({"note": "the issue changed after your review: review it again"} if stale else {})
        rows.append({"issue_id": o.id, "question_id": qid, "kind": o.kind, "requirement_ids": o.requirement_ids, "question": o.question,
                     "source": o.source, "class": cls, "resolved_in_contract": o.resolved, "resolution": o.resolution, **detail})
    return rows


def write_report(project, step_name: str, contract, auto_defaults: dict[str, str], docs_dir: Path, now: str) -> dict:
    answers = load_answers(project.schemas_dir / "questions" / f"{step_name}.answers.json")
    decisions = read_json(decisions_path(project), default={}) or {}
    rows = ledger(contract, answers, decisions, auto_defaults)
    reqs = contract.requirements
    count = lambda f: sum(1 for r in reqs if f(r))  # noqa: E731
    data = {"schema_version": 1, "generated_at": now, "contract_hash": contract.metadata.contract_hash, "contract_status": contract.metadata.status,
            "issues": rows, "summary": {c: sum(1 for r in rows if r["class"] == c) for c in CLASSES},
            "requirements": {s: count(lambda r, s=s: r.status == s) for s in ("planned", "open", "blocked", "not_observable", "excluded", "withdrawn", "draft")},
            "assumption_candidates_decided_normative": [{"req_id": r.req_id, "reason": r.status_reason} for r in reqs
                                                        if r.assumption_evidence and r.origin_class == "NORMATIVE"]}
    write_json(project.schemas_dir / "dv_review.json", data)
    docs_dir.mkdir(parents=True, exist_ok=True)
    (docs_dir / "dv_review_report.md").write_text(render(data, contract))
    return data


def render(data: dict, contract) -> str:
    s = data["summary"]
    out = [f"# DUT-DV review report — {contract.metadata.ip_name}", "",
           f"Contract `{data['contract_hash'] or '(not frozen)'}` ({data['contract_status']}); generated by Q3TUI, do not edit.", "",
           "This report says who decided each open issue. A planning artifact is not simulation evidence (DUT-DV-011).", "",
           f"| decided by you (answer) | decided by you (default accepted) | auto default (no review) | pending |", "|---|---|---|---|",
           f"| {s['user_answered']} | {s['user_accepted_default']} | {s['auto_default']} | {s['pending']} |", "", "## Open issues", ""]
    for cls, title in (("user_answered", "Answered by you"), ("user_accepted_default", "Reviewed by you, default accepted"),
                       ("auto_default", "Auto default (not reviewed)"), ("pending", "Pending")):
        rows = [r for r in data["issues"] if r["class"] == cls]
        if not rows:
            continue
        out += [f"### {title}", ""]
        for r in rows:
            out.append(f"- **{r['issue_id']}** ({', '.join(r['requirement_ids'])}; {r['source']}): {r['question']}")
            if cls == "user_answered":
                out.append(f"  - answer: {r['answer']}")
                out.append(f"  - in the contract: {'resolved: ' + r['resolution'] if r['resolved_in_contract'] else 'NOT applied yet'}")
            elif cls == "user_accepted_default":
                out.append(f"  - default: {r['default']} — accepted by {r['by']} at {r['at']}" + (f" ({r['note']})" if r["note"] else ""))
            elif cls == "pending" and r.get("note"):
                out.append(f"  - {r['note']}")
            elif cls == "auto_default":
                out.append(f"  - default accepted automatically: {r['default']}")
        out.append("")
    q = data["requirements"]
    out += ["## Requirements", "", "| planned | open | blocked | not observable | excluded |", "|---|---|---|---|---|",
            f"| {q['planned']} | {q['open']} | {q['blocked']} | {q['not_observable']} | {q['excluded']} |", ""]
    if data["assumption_candidates_decided_normative"]:
        out += ["## Assumption candidates decided as normative", ""] + [f"- {x['req_id']}: {x['reason'] or '(no reason)'}" for x in data["assumption_candidates_decided_normative"]]
    return "\n".join(out) + "\n"
