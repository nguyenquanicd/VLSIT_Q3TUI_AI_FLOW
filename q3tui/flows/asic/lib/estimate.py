"""A quick estimate of the clock the ASIC library allows (`asic_estimate`): Design Compiler at low effort, constrained by the clocks only.

The full synthesis (`asic_synth`) takes minutes; this takes about a minute and answers one question — how fast could this RTL run in this
library — so the number can sit next to the frequency you type in the SDC. The clocks get a probe period (1 ns, or the technology's `probe_ns` in the catalog: tighter for a faster node; when the library meets it, half of the period the worst path then needed, up to three runs, and the best result of the runs counts: the tool's result at a moderate violation is erratic on a fast library), so the
worst register-to-register path shows as a violation and the Fmax is `1000 / (probe − slack)` (clock-to-Q, logic, setup and uncertainty are
in the slack). No I/O delays: they scale with the period and would make the formula wrong; ports are not part of this estimate. Low effort
maps a little slower than `compile_ultra`: the estimate leans pessimistic (on the sample block 242 MHz against 240+ met and 254 estimated
by the full run). Written to `schemas/asic_estimate.json`; the full synthesis, when fresh, wins in `lib/hints.py`."""

from __future__ import annotations

import time
from pathlib import Path

from q3tui.core.project import write_json
from q3tui.eda import tools as toolmod
from q3tui.flows.asic.lib import dc, pdks
from q3tui.flows.fpga.lib import hints
from q3tui.flows.fpga.lib import sdc as sdcmod

PROBE_NS = 1.0  # the first probe unless the technology's catalog entry says another (`probe_ns`): a period the library cannot meet
MAX_PROBES = 3  # a probe the library meets says only "at least": the next is half of what the path needed, and the best result of the runs counts
ESTIMATE_JSON = "asic_estimate.json"
QUICK_COMPILE = "compile -map_effort low -area_effort none"


def probe_tcl(cfg: "sdcmod.SdcConfig", probe_ns: float = PROBE_NS) -> str:
    """The constraints of the estimate: every clock at the probe period (same uncertainty as the SDC's), nothing else."""
    lines = [f"# generated by Q3TUI (asic_estimate): the clocks at {probe_ns:g} ns, no I/O constraints"]
    for c in cfg.clocks:
        lines.append(f"create_clock -name {c.name} -period {probe_ns:g} [get_ports {c.port}]")
        if c.uncertainty_ns:
            lines.append(f"set_clock_uncertainty {c.uncertainty_ns:g} [get_clocks {c.name}]")
    return "\n".join(lines) + "\n"


def run(ops) -> str:
    """The action: `compute`, and the result in the step's log."""
    msg = compute(ops)
    name = next((s.name for s in ops.engine.steps if s.kind.endswith(".sdc")), ops.engine.steps[0].name)
    return ops._log(name, msg)


def compute(ops) -> str:
    """Estimate the ASIC Fmax of every clock of the SDC for the library of the ASIC flow's `asic_synth` (its options); writes
    `schemas/asic_estimate.json` and returns the message. Runs the tool (about a minute): the TUI calls it in a thread."""
    from q3tui import flows
    from q3tui.pipeline.engine import Engine, EngineError

    eng = ops.engine if ops.engine.flow.name == "asic" else Engine(ops.project, flow=flows.load_flow("asic", ops.project.root))
    step = next((s for s in eng.steps if s.kind == "asic.asic_synth"), None)
    if step is None:
        raise EngineError("the ASIC flow has no asic_synth step")
    cfg = sdcmod.load(ops.project)
    if cfg is None or not cfg.clocks:
        raise EngineError("no clock yet: run the sdc step first (constraints/sdc/sdc.json)")
    problem = step.missing_rtl(eng)
    if problem:
        raise EngineError(problem)
    libs = step.libraries(eng)
    if not libs or any(not Path(x).is_file() for x in libs):
        raise EngineError("no library: set `library` (the .db of the standard cells) in Settings → asic_synth")
    tools = step.tools(eng)
    if not toolmod.available(tools, "asic_synth"):
        raise EngineError("the `asic_synth` tool (Design Compiler) was not found (module synopsys/syn; see `q3tui tools check`)")
    top = step.top(eng)
    work = ops.project.state_dir / "asic" / "estimate"
    work.mkdir(parents=True, exist_ok=True)
    for f in (*dc.REPORTS, "dc.out", "dc.log"):
        (work / f).unlink(missing_ok=True)
    probe, script = work / "probe.tcl", work / "estimate.tcl"
    t0 = time.monotonic()
    groups: list[dict] = []
    found = pdks.locate(libs[0], ops.project)
    used = (found[0].probe_ns if found else 0) or PROBE_NS
    best: dict[str, dict] = {}  # per clock: the run that got furthest
    ran = used
    for _ in range(MAX_PROBES):
        ran = used
        probe.write_text(probe_tcl(cfg, used))
        script.write_text(dc.script_text(step.rtl_files(eng), top, libs, probe, work, work / "net" / f"{top}.v", {**step.options, "compile": QUICK_COMPILE, "max_paths": 1}))
        for f in (*dc.REPORTS, "dc.out"):
            (work / f).unlink(missing_ok=True)
        res = toolmod.run_role(tools, "asic_synth", work, {"script": script, "top": top, "filelist": step.filelist(eng), "files": step.rtl_files(eng), "workdir": work},
                               log_name="dc.out")
        toolmod.check_broken(res, "asic_synth")
        if not res.ok or not (work / "qor.rpt").is_file():
            errs = "; ".join(d.message for d in res.errors[:3]) or "no report was written"
            raise EngineError(f"the estimate failed: {errs} (log: {res.log_path})")
        groups = dc.parse_groups((work / "qor.rpt").read_text(errors="replace"), {c.name: used for c in cfg.clocks})
        if not groups:
            raise EngineError(f"the estimate found no clock path group (log: {res.log_path}): no register is clocked by a clock of the SDC")
        for g in groups:
            old = best.get(g["group"])
            if old is None or (g["fmax_mhz"] or 0) > (old["fmax_mhz"] or 0) or ((g["fmax_mhz"] or 0) == (old["fmax_mhz"] or 0) and g["bound"] == "estimate"):
                best[g["group"]] = g  # (the same path delay from a violated run is the tool's limit, from a met run only what it stopped at)
        groups = list(best.values())
        met = [g for g in groups if g["bound"] == "at_least"]
        if not met:  # every clock missed the probe: the slack says how far
            break
        used = round(max(0.05, 0.5 * min(g["period_ns"] - g["slack_ns"] for g in met)), 3)  # the met clocks: half of what their path needed (the best run of a clock stays)
    fmax = min((g["fmax_mhz"] for g in groups if g["fmax_mhz"]), default=None)
    ver = dc.parse_version(Path(res.log_path).read_text(errors="replace")) if res.log_path else "Design Compiler"
    write_json(ops.project.schemas_dir / ESTIMATE_JSON, {"mode": "quick", "tool": ver, "top": top, "library": libs, "probe_ns": ran,
                                                         "rtl_sha": hints.rtl_sha(ops.project), "runtime_s": round(time.monotonic() - t0, 1),
                                                         "timing": {"fmax_mhz": fmax, "groups": groups}})
    return ("ASIC estimate (quick, " + f"{time.monotonic() - t0:.0f} s): " + "; ".join(
        f"{g['group']} {'≥' if g['bound'] == 'at_least' else '≈'} {g['fmax_mhz']:g} MHz" for g in groups if g["fmax_mhz"])
            + f" in {', '.join(pdks.short_name(x, ops.project) for x in libs)}")
