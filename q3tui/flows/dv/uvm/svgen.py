"""Small helpers of the deterministic UVM scaffold: SystemVerilog names and ranges from the contract, region markers, merging.

Region markers make agent-authored and hand-written code distinguishable from the scaffold and keep it across regeneration
(DUT-DV-013, 014):

    // DV_REGION(<id>) BEGIN scaffold   ... stub with DV_TODO(<id>) ...
    // DV_REGION(<id>) END

An owner other than `scaffold` (`agent`, `user`) in the BEGIN line marks code that is not generated: it is kept verbatim."""

from __future__ import annotations

import re

REGION_RE = re.compile(r"^([ \t]*)// DV_REGION\(([A-Za-z0-9_.\-]+)\) BEGIN (\w+)[^\n]*\n(.*?)^[ \t]*// DV_REGION\(\2\) END[^\n]*\n", re.S | re.M)
TODO_RE = re.compile(r"DV_TODO\(([A-Za-z0-9_.\-]+)")
HEADER_MARK = "DV_SCAFFOLD"


def lc(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")


def sv_range(width: str) -> str:
    """Packed range of a width as the specification writes it: `1` -> none, `PR_X` -> [(PR_X)-1:0], `[A-1:0][B-1:0]` as is."""
    w = width.strip().strip("`")
    if w.startswith("["):
        return w
    return "" if w == "1" else f"[({w})-1:0]"


def sv_str(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', "'").replace("\n", " ")


def region(rid: str, body: str, indent: str = "") -> str:
    """A scaffold-owned region: the stub lines between the markers (the body carries a DV_TODO(<id>) announcement)."""
    lines = body.rstrip("\n").split("\n")
    return "\n".join([f"{indent}// DV_REGION({rid}) BEGIN scaffold", *[f"{indent}{ln}" if ln else "" for ln in lines], f"{indent}// DV_REGION({rid}) END"]) + "\n"


def regions(text: str) -> dict[str, tuple[str, str]]:
    """region id -> (owner, whole region text incl. markers)."""
    return {m.group(2): (m.group(3), m.group(0)) for m in REGION_RE.finditer(text)}


def merge(new: str, old: str) -> tuple[str, list[str]]:
    """The regenerated text with the regions the engineer or the agent took over (owner not `scaffold`) kept from the old file.
    Returns (text, ids kept)."""
    kept: list[str] = []
    olds = regions(old)

    def pick(m: re.Match) -> str:
        rid = m.group(2)
        if rid in olds and olds[rid][0] != "scaffold":
            kept.append(rid)
            return olds[rid][1]
        return m.group(0)

    return REGION_RE.sub(pick, new), kept


def file_header(project: str, author: str, day: str, desc: str, contract_hash: str) -> str:
    return (f"// {HEADER_MARK}: generated by Q3TUI (uvm_vip backend) from the verification contract {contract_hash[:12] or 'draft'}.\n"
            f"// Project: {project} | Author: {author} (user) | AI flow: VLSIT Q3TUI | Date: {day}\n"
            f"// {desc}\n"
            f"// Code between `DV_REGION(id) BEGIN scaffold` and `END` is generated; change BEGIN scaffold to BEGIN agent / BEGIN user\n"
            f"// when you implement it: such a region is kept when the scaffold is regenerated.\n")


_HEADER_LINE = re.compile(r"^// (DV_SCAFFOLD:|Project:|Code between|when you implement).*\n", re.M)


def outside(text: str) -> str:
    """The text without its DV regions and its header: what a regeneration must find unchanged to merge instead of keeping the file."""
    return _HEADER_LINE.sub("", REGION_RE.sub("", text))
